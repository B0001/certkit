"""
Scratch experiment for certkit-ph1 (session 6).

Sessions 1-5 closed off matvec-oracle subspace methods (proven infeasible
worst-case), low-Pauli-term-count exploitation (not viable for q<=14), the
already-in-repo banded/Sturm route (structurally inapplicable to PauliSumReal
past ~7 qubits -- a single-qubit term's bit-flip mask alone gives bandwidth
~n/2), and FEAST/contour-integral counting (soundness-incompatible, needs
stochastic trace estimation). Session 5's handoff flagged one remaining
untried door: a fill-reducing SPARSE (not banded) elimination order for the
LDL^T inertia count, e.g. nested dissection or greedy minimum-degree, applied
to the actual sparsity graph of a Pauli-sum operator rather than to its
index-order bandwidth.

This script checks that door computationally instead of leaving it as a
hand-wave.

Key fact about the sparsity graph: a PauliSumReal term with mask != 0 (any
X/Y factor) connects computational basis state i to i^mask, for every i. So
the sparsity graph of the whole operator is exactly the Cayley graph on
Z_2^q generated by the *set of distinct masks* appearing in the term list
(diagonal Z-only terms contribute mask=0, i.e. no edges -- they only affect
diagonal entries, never fill). For TFIM (examples/sample/pauli_operator.json,
one X per qubit + nearest-neighbor ZZ), the generator set is exactly the q
single-bit vectors, so the graph is exactly the q-dimensional hypercube Q_q.

Two things measured, both stdlib-only (no numpy needed for symbolic work):

1. A closed-form, elementary lower bound on how well ANY balanced vertex
   separator of Q_q can do: the "middle-layer" cut. Vertices split by
   Hamming weight; edges only connect weight w to weight w+-1, so removing
   the layer(s) at weight floor(q/2) (and ceil(q/2) when q is even, to keep
   the two sides strictly non-adjacent) disconnects {weight < q/2} from
   {weight > q/2}. Both sides are within a factor of 2 of n/2 for the q
   tested (printed explicitly, not assumed). This is a *constructive upper
   bound* on the minimum separator (a specific cut that works), not a
   claim that no smaller separator exists -- but per the standard hypercube
   vertex-isoperimetric result (Harper), Hamming-ball/layer cuts are known
   to be asymptotically optimal for this graph, so it is a reasonable proxy
   for "the best any fill-reducing order could hope to do here", not a
   strawman.

2. A direct measurement: run greedy minimum-degree symbolic elimination
   (the standard practical fill-reducing heuristic used by real sparse
   solvers, e.g. SuiteSparse/CHOLMOD) on the actual sparsity graph and
   record the fill-in produced and an operation-count proxy (sum of
   pivot-degree^2, which tracks LDL^T arithmetic cost), for both the pure
   hypercube (TFIM-shaped) case and a JW two-body chemistry-shaped case
   (reusing the from-scratch JW transform from
   certkit-ph1-jw-termcount-experiment.py to get realistic masks).
"""
import math
import random
import time
from collections import defaultdict

import importlib.util
import os

_jw_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "certkit-ph1-jw-termcount-experiment.py")
_spec = importlib.util.spec_from_file_location("certkit_ph1_jw_termcount_experiment", _jw_path)
jwmod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(jwmod)


def middle_layer_separator(q):
    n = 1 << q
    # Removing the single layer L = q//2 disconnects {weight<L} from
    # {weight>L}: edges only connect weights differing by exactly 1, and
    # L-1, L+1 differ by 2, so a single layer suffices as a separator.
    L = q // 2
    below = sum(math.comb(q, w) for w in range(0, L))
    sep = math.comb(q, L)
    above = sum(math.comb(q, w) for w in range(L + 1, q + 1))
    return n, below, sep, above


def hypercube_masks(q):
    return [1 << k for k in range(q)]


def jw_masks(M, seed=1, two_body=True):
    """Distinct nonzero bit-flip masks appearing in a random JW-mapped
    one(+two)-body electronic-structure-shaped Hamiltonian on M qubits."""
    rng = random.Random(seed)
    acc = {}
    h1 = [[0.0] * M for _ in range(M)]
    for p in range(M):
        for q_ in range(p, M):
            v = rng.uniform(-1, 1)
            h1[p][q_] = v
            h1[q_][p] = v
    for p in range(M):
        for q_ in range(M):
            if h1[p][q_] == 0.0:
                continue
            terms = jwmod.mul_terms(jwmod.jw_ladder(p, M, True), jwmod.jw_ladder(q_, M, False))
            jwmod.add_into(acc, terms, h1[p][q_])
    if two_body:
        seen = {}
        for p in range(M):
            for q_ in range(M):
                for r in range(M):
                    for s in range(M):
                        if p == q_ or r == s:
                            continue
                        canon = min((p, q_, r, s), (q_, p, s, r))
                        if canon not in seen:
                            seen[canon] = rng.uniform(-1, 1)
                        v = seen[canon]
                        if (p, q_, r, s) not in [canon, (canon[1], canon[0], canon[3], canon[2])]:
                            continue
                        if v == 0.0:
                            continue
                        terms = jwmod.mul_terms(
                            jwmod.mul_terms(jwmod.jw_ladder(p, M, True), jwmod.jw_ladder(q_, M, True)),
                            jwmod.mul_terms(jwmod.jw_ladder(r, M, False), jwmod.jw_ladder(s, M, False)),
                        )
                        jwmod.add_into(acc, terms, 0.5 * v)
    masks = set()
    for s, c in acc.items():
        if abs(c) <= 1e-9:
            continue
        mask = 0
        for k, ch in enumerate(s):
            if ch in ("X", "Y"):
                mask |= 1 << k
        if mask:
            masks.add(mask)
    return sorted(masks)


def min_degree_fill(n, masks, time_budget_s=25.0):
    """Greedy minimum-degree symbolic elimination on the Cayley graph
    generated by `masks` over Z_2^{log2 n}. Returns (total_fill_edges,
    total_op_proxy, max_degree_seen, completed) where completed is False if
    the time budget ran out (partial result, honestly reported as such)."""
    adj = [set() for _ in range(n)]
    for i in range(n):
        for m in masks:
            adj[i].add(i ^ m)
    for i in range(n):
        adj[i].discard(i)

    remaining = set(range(n))
    total_fill = 0
    total_ops = 0
    max_deg = 0
    t0 = time.time()
    completed = True
    steps = 0
    while remaining:
        if time.time() - t0 > time_budget_s:
            completed = False
            break
        v = min(remaining, key=lambda x: len(adj[x]))
        nbrs = [u for u in adj[v] if u in remaining]
        d = len(nbrs)
        max_deg = max(max_deg, d)
        total_ops += d * d
        for i in range(len(nbrs)):
            a = nbrs[i]
            for j in range(i + 1, len(nbrs)):
                b = nbrs[j]
                if b not in adj[a]:
                    adj[a].add(b)
                    adj[b].add(a)
                    total_fill += 1
        for u in nbrs:
            adj[u].discard(v)
        remaining.discard(v)
        steps += 1
    return total_fill, total_ops, max_deg, completed, steps


if __name__ == "__main__":
    print("=== 1. middle-layer separator size vs n, hypercube Q_q ===")
    print(f"{'q':>4} {'n':>10} {'below':>10} {'sep':>10} {'above':>10} {'sep/n':>10}")
    for q in [6, 8, 10, 12, 14, 16, 20, 24]:
        n, below, sep, above = middle_layer_separator(q)
        print(f"{q:>4} {n:>10} {below:>10} {sep:>10} {above:>10} {sep / n:>10.4f}")

    print()
    print("=== 2a. greedy min-degree fill, TFIM-shaped (pure hypercube) ===")
    print(f"{'q':>4} {'n':>8} {'fill_edges':>12} {'op_proxy':>14} {'max_deg':>9} {'dense_n^3':>14} {'ops/n^3':>10} {'complete':>9}")
    for q in [4, 6, 8, 10, 11, 12]:
        n = 1 << q
        masks = hypercube_masks(q)
        fill, ops, maxd, done, steps = min_degree_fill(n, masks, time_budget_s=90.0)
        print(f"{q:>4} {n:>8} {fill:>12} {ops:>14} {maxd:>9} {n**3:>14} {ops / n**3:>10.5f} {str(done):>9}"
              + ("" if done else f"  (partial: {steps}/{n} pivots eliminated)"))

    print()
    print("=== 2b. greedy min-degree fill, JW two-body chemistry-shaped ===")
    print(f"{'M':>4} {'n':>8} {'#masks':>7} {'fill_edges':>12} {'op_proxy':>14} {'max_deg':>9} {'dense_n^3':>14} {'ops/n^3':>10} {'complete':>9}")
    for M in [4, 6, 8, 10, 11]:
        n = 1 << M
        masks = jw_masks(M, seed=1, two_body=True)
        fill, ops, maxd, done, steps = min_degree_fill(n, masks, time_budget_s=90.0)
        print(f"{M:>4} {n:>8} {len(masks):>7} {fill:>12} {ops:>14} {maxd:>9} {n**3:>14} {ops / n**3:>10.5f} {str(done):>9}"
              + ("" if done else f"  (partial: {steps}/{n} pivots eliminated)"))
